#!/usr/bin/env node
// Generate the TypeScript view of the desktop v2 protocol from the JSON Schema
// that the Rust contract crate publishes (design 4.6, D8): the three sides must
// not maintain field semantics by hand. The schema file is the source of truth;
// what this writes is derived, committed, and checked for drift with --check.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'contracts/desktop-v2/schema.json');
const outDir = resolve(root, 'packages/desktop-api/src/generated');
const typesPath = resolve(outDir, 'envelope.ts');
const schemaModulePath = resolve(outDir, 'schema.ts');

const schemaText = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(schemaText);
const digest = createHash('sha256').update(schemaText).digest('hex');

const banner = (what) =>
  `/**\n * ${what}\n *\n * Generated by scripts/gen-types.mjs from contracts/desktop-v2/schema.json.\n * Schema sha256: ${digest}\n * Do not edit: change the Rust contract, re-export the schema, and regenerate.\n */\n`;

const types = await compile(schema, 'Envelope', {
  bannerComment: banner('The desktop v2 protocol as TypeScript types.'),
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: true,
  unknownAny: true,
  strictIndexSignatures: true,
  format: true,
  cwd: dirname(schemaPath),
});

const schemaModule =
  `${banner('The published envelope schema, for strict validation at runtime.')}\n` +
  `export const schemaSha256 = '${digest}';\n\n` +
  `export const envelopeSchema: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`;

const outputs = [
  [typesPath, types],
  [schemaModulePath, schemaModule],
];

// The bounded computer image pipe has its own schema. It is not part of the
// control envelope, but its TypeScript DTOs follow the same Rust-owned source.
const computerSchemaPath = resolve(root, 'contracts/computer-v1/schema.json');
const computerSchemaText = readFileSync(computerSchemaPath, 'utf8');
const computerSchema = JSON.parse(computerSchemaText);
const computerDigest = createHash('sha256').update(computerSchemaText).digest('hex');
const computerBanner = `/**\n * The private computer-use protocol as TypeScript types.\n *\n * Generated by scripts/gen-types.mjs from contracts/computer-v1/schema.json.\n * Schema sha256: ${computerDigest}\n * Do not edit: change the Rust contract, re-export the schema, and regenerate.\n */\n`;
const computerTypes = await compile(computerSchema, 'ComputerWireContract', {
  bannerComment: computerBanner,
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: true,
  unknownAny: true,
  strictIndexSignatures: true,
  format: true,
  cwd: dirname(computerSchemaPath),
});
outputs.push([resolve(outDir, 'computer.ts'), computerTypes]);
outputs.push([
  resolve(outDir, 'computer-schema.ts'),
  `${computerBanner}\nexport const computerSchemaSha256 = '${computerDigest}';\n\n` +
    `export const computerWireSchema: Record<string, unknown> = ${JSON.stringify(computerSchema, null, 2)};\n`,
]);

// Browser page evidence has no native window, AX action or global coordinate fields.
const browserSchemaPath = resolve(root, 'contracts/browser-v1/schema.json');
const browserSchemaText = readFileSync(browserSchemaPath, 'utf8');
const browserSchema = JSON.parse(browserSchemaText);
const browserDigest = createHash('sha256').update(browserSchemaText).digest('hex');
const browserBanner = `/**\n * Page evidence types generated from the Rust browser contract.\n *\n * Generated by scripts/gen-types.mjs from contracts/browser-v1/schema.json.\n * Schema sha256: ${browserDigest}\n * Do not edit: change the Rust contract, re-export the schema, and regenerate.\n */\n`;
const browserTypes = await compile(browserSchema, 'BrowserWireContract', {
  bannerComment: browserBanner,
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: true,
  unknownAny: true,
  strictIndexSignatures: true,
  format: true,
  cwd: dirname(browserSchemaPath),
});
outputs.push([resolve(outDir, 'browser.ts'), browserTypes]);
outputs.push([
  resolve(outDir, 'browser-schema.ts'),
  `${browserBanner}\nexport const browserSchemaSha256 = '${browserDigest}';\n\n` +
    `export const browserWireSchema: Record<string, unknown> = ${JSON.stringify(browserSchema, null, 2)};\n`,
]);

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [path, text] of outputs) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current !== text) {
      console.error(`stale: ${path.replace(root + '/', '')} differs from what the schema generates`);
      stale = true;
    }
  }
  if (stale) {
    console.error('run `npm run gen-types` and commit the result');
    process.exit(1);
  }
  console.log(`generated types are current (schema sha256 ${digest.slice(0, 12)})`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [path, text] of outputs) {
    writeFileSync(path, text);
    console.log(`wrote ${path.replace(root + '/', '')}`);
  }
}
