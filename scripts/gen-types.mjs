#!/usr/bin/env node
// Generate the TypeScript view of the desktop v1 protocol from the JSON Schema
// that the Rust contract crate publishes (design 4.6, D8): the three sides must
// not maintain field semantics by hand. The schema file is the source of truth;
// what this writes is derived, committed, and checked for drift with --check.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'contracts/desktop-v1/schema.json');
const outDir = resolve(root, 'packages/desktop-api/src/generated');
const typesPath = resolve(outDir, 'envelope.ts');
const schemaModulePath = resolve(outDir, 'schema.ts');

const schemaText = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(schemaText);
const digest = createHash('sha256').update(schemaText).digest('hex');

const banner = (what) =>
  `/**\n * ${what}\n *\n * Generated by scripts/gen-types.mjs from contracts/desktop-v1/schema.json.\n * Schema sha256: ${digest}\n * Do not edit: change the Rust contract, re-export the schema, and regenerate.\n */\n`;

const types = await compile(schema, 'Envelope', {
  bannerComment: banner('The desktop v1 protocol as TypeScript types.'),
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: true,
  unknownAny: true,
  strictIndexSignatures: true,
  format: true,
  cwd: dirname(schemaPath),
});

const schemaModule =
  `${banner('The published envelope schema, for strict validation at runtime.')}\n` +
  `export const schemaSha256 = '${digest}';\n\n` +
  `export const envelopeSchema: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`;

const outputs = [
  [typesPath, types],
  [schemaModulePath, schemaModule],
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [path, text] of outputs) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current !== text) {
      console.error(`stale: ${path.replace(root + '/', '')} differs from what the schema generates`);
      stale = true;
    }
  }
  if (stale) {
    console.error('run `npm run gen-types` and commit the result');
    process.exit(1);
  }
  console.log(`generated types are current (schema sha256 ${digest.slice(0, 12)})`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [path, text] of outputs) {
    writeFileSync(path, text);
    console.log(`wrote ${path.replace(root + '/', '')}`);
  }
}
